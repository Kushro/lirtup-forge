//! Stats collection: fills `lirtup_proto::StatsSample` every 500 ms and the
//! stats panel (`stats.py`). Front S, round 2.
//!
//! - [`Stats`] lives on the session thread. The session thread records
//!   captures, CPU render time, dirty area and GPU timestamps directly; every
//!   present (real or generated, from the session thread or the frame
//!   generation present thread) arrives through a [`PresentSink`].
//! - [`Stats::poll`] drains the sink, writes the latency CSV
//!   ([`crate::latency`]) and, every `sample_interval`, returns the
//!   [`StatsSample`] the session thread sends as `Event::Stats`.
//! - [`StatsPanel`] draws the panel (`show_stats`, `ToggleStats`) from the
//!   same sample, so the GUI and the panel show the same numbers. Since
//!   round 4 (front T) it is drawn with `lirtup_effects::ui_draw` on the
//!   dark glass of the design, in JetBrains Mono.

