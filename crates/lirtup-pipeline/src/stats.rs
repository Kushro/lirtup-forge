/// What was presented.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum FrameKind {
    /// A frame made from a captured one (`real` in the CSV).
    Real,
    /// A frame generated by lsfg (`generated` in the CSV).
    Generated,
}

impl FrameKind {
    /// The CSV spelling (`real`, `generated`).
    pub fn as_str(self) -> &'static str {
        match self {
            FrameKind::Real => "real",
            FrameKind::Generated => "generated",
        }
    }
}

/// One present.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct PresentRecord {
    /// When the game frame it came from was captured (`None` for a repeat
    /// of an unchanged frame: no latency).
    pub capture: Option<Instant>,
    /// When it was handed to the swapchain.
    pub presented: Instant,
    /// Real or generated.
    pub kind: FrameKind,
    /// Frame generation multiplier in effect (1 = off).
    pub multiplier: u8,
}

/// Where presents are reported. `Clone + Send + Sync`; never blocks (a full
/// queue drops the record and counts it).
#[derive(Debug, Clone)]
pub struct PresentSink {
    tx: Sender<PresentRecord>,
}

impl PresentSink {
    /// Report one present.
    pub fn record(&self, record: PresentRecord) {
        let _ = self.tx.try_send(record);
    }
}

/// How the stats are collected.
