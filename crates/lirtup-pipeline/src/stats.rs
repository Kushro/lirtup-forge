/// Seconds of history behind each rate (1.x `_WINDOW`).
const WINDOW: Duration = Duration::from_secs(1);
/// Presents that fit in the sink between two polls.
const SINK_CAPACITY: usize = 4096;
/// Weight of the newest GPU time in the smoothed value (1.x: 0.2).
const GPU_SMOOTHING: f64 = 0.2;
/// Below this game frame rate (a still image) the GPU budget is not checked.
const MIN_BUDGET_FPS: f32 = 5.0;
/// The budget is never looser than this rate (see `stats.py`: a slower
/// measured rate cannot tell slow content from content slowed down by the
/// effects themselves).
const TARGET_FPS: f32 = 30.0;
/// Stages named in a GPU warning.
const HEAVIEST: usize = 3;

/// What was presented.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum FrameKind {
    /// A frame made from a captured one (`real` in the CSV).
    Real,
    /// A frame generated by lsfg (`generated` in the CSV).
    Generated,
}

impl FrameKind {
    /// The CSV spelling (`real`, `generated`).
    pub fn as_str(self) -> &'static str {
        match self {
            FrameKind::Real => "real",
            FrameKind::Generated => "generated",
        }
    }
}

/// One present.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct PresentRecord {
    /// When the game frame it came from was captured (`None` for a repeat
    /// of an unchanged frame: no latency).
    pub capture: Option<Instant>,
    /// When it was handed to the swapchain.
    pub presented: Instant,
    /// Real or generated.
    pub kind: FrameKind,
    /// Frame generation multiplier in effect (1 = off).
    pub multiplier: u8,
}

/// Where presents are reported. `Clone + Send + Sync`; never blocks (a full
/// queue drops the record and counts it).
#[derive(Debug, Clone)]
pub struct PresentSink {
    tx: Sender<PresentRecord>,
}

impl PresentSink {
    /// Report one present.
    pub fn record(&self, record: PresentRecord) {
        if let Err(TrySendError::Full(_)) = self.tx.try_send(record) {
            tracing::debug!("stats: present queue full, record dropped");
        }
    }
}

/// How the stats are collected.
#[derive(Debug, Clone, PartialEq)]
pub struct StatsOptions {
    /// How often [`Stats::poll`] returns a sample (500 ms, as the 1.x panel).
    pub sample_interval: Duration,
    /// Display refresh rate (budget of the GPU warning, generated fps cap).
    pub refresh_hz: f32,
    /// `latency_log`: write one CSV row per present.
    pub latency_csv: Option<PathBuf>,
}

/// Events per second over the last [`WINDOW`] (1.x `_Rate`).
#[derive(Debug, Default)]
struct Rate {
    times: VecDeque<Instant>,
}

impl Rate {
    fn add(&mut self, now: Instant) {
        self.times.push_back(now);
    }

    fn per_second(&mut self, now: Instant) -> f32 {
        expire(&mut self.times, now, |t| *t);
        self.times.len() as f32 / WINDOW.as_secs_f32()
    }
}

/// Drop the entries older than [`WINDOW`] at the front of `queue`.
fn expire<T>(queue: &mut VecDeque<T>, now: Instant, at: impl Fn(&T) -> Instant) {
    while queue
        .front()
        .is_some_and(|e| now.saturating_duration_since(at(e)) > WINDOW)
    {
        queue.pop_front();
    }
}

/// The stats of one session.
pub struct Stats {
    options: StatsOptions,
    tx: Sender<PresentRecord>,
    rx: Receiver<PresentRecord>,
    log: Option<LatencyLog>,
    /// Every capture (polled) and the ones with a new frame.
    captures: Rate,
    new_frames: Rate,
    presents: Rate,
    generated: Rate,
    /// `(when, cpu ms)` of full renders.
    /// `(when, render without waits, waits)`, ms.
    render_ms: VecDeque<(Instant, f32, f32)>,
    /// `(present, latency ms, kind)` of presents with a capture time.
    latency: VecDeque<(Instant, f32, FrameKind)>,
    /// Smoothed GPU ms per pass label, in dispatch order.
    gpu: Vec<(String, f64)>,
    gpu_total: Option<f64>,
    dirty_fraction: f32,
    tiles: Option<u32>,
    multiplier: Option<u8>,
    next_sample: Instant,
    latest: Option<StatsSample>,
}

impl Stats {
    /// Start collecting (opens the latency CSV if asked).
    ///
    /// A CSV that cannot be created is logged and skipped, as in 1.x: the
    /// session runs anyway.
    pub fn new(options: StatsOptions) -> Result<Stats> {
        let now = Instant::now();
        let log = options
            .latency_csv
            .as_deref()
            .and_then(|path| match LatencyLog::create(path, now) {
                Ok(log) => {
                    tracing::info!("logging frame latency to {}", path.display());
                    Some(log)
                }
                Err(e) => {
                    tracing::error!("cannot write the latency log {}: {e}", path.display());
                    None
                }
            });
        let (tx, rx) = crossbeam_channel::bounded(SINK_CAPACITY);
        Ok(Stats {
            next_sample: now + options.sample_interval,
            options,
            tx,
            rx,
            log,
            captures: Rate::default(),
            new_frames: Rate::default(),
            presents: Rate::default(),
            generated: Rate::default(),
            render_ms: VecDeque::new(),
            latency: VecDeque::new(),
            gpu: Vec::new(),
            gpu_total: None,
            dirty_fraction: 0.0,
            tiles: None,
            multiplier: None,
            latest: None,
        })
    }

    /// A sink for presents, for the presenter and the frame generation
    /// thread.
    pub fn sink(&self) -> PresentSink {
        PresentSink { tx: self.tx.clone() }
    }

    /// One capture: `new_frame` if the window changed (capture fps counts
    /// only new frames, like 1.x).
    pub fn record_capture(&mut self, now: Instant, new_frame: bool) {
        self.captures.add(now);
        if new_frame {
            self.new_frames.add(now);
        }
    }

    /// CPU time of the frame (upload, record, submit), in ms, and of it
    /// the time spent waiting to present (`wait_ms`, shown apart).
    pub fn record_render(&mut self, cpu_ms: f32, wait_ms: f32) {
        self.render_ms
            .push_back((Instant::now(), (cpu_ms - wait_ms).max(0.0), wait_ms));
    }

    /// Fraction of the frame that changed, and the tiles processed (`None`
    /// in full-frame mode).
    pub fn record_dirty(&mut self, fraction: f32, tiles: Option<u32>) {
        self.dirty_fraction = fraction.clamp(0.0, 1.0);
        self.tiles = tiles;
    }

    /// GPU timestamps of the last frame (per pass label; «ms por etapa»).
    ///
    /// Each label is smoothed as 1.x (`0.8 · old + 0.2 · new`); labels that
    /// are no longer in the frame (the chain changed) are dropped.
    pub fn set_gpu_times(&mut self, times: &Timestamps) {
        let mut next: Vec<(String, f64)> = Vec::with_capacity(times.dispatches.len());
        for (label, ms) in &times.dispatches {
            if let Some(entry) = next.iter_mut().find(|(l, _)| l == label) {
                // Several dispatches of one pass (bloom, MagpieFX passes).
                entry.1 += ms;
            } else {
                next.push((label.clone(), *ms));
            }
        }
        for (label, ms) in &mut next {
            if let Some((_, old)) = self.gpu.iter().find(|(l, _)| l == label) {
                *ms = smooth(*old, *ms);
            }
        }
        self.gpu = next;
        self.gpu_total = Some(match self.gpu_total {
            Some(old) => smooth(old, times.total_ms),
            None => times.total_ms,
        });
    }

    /// Nobody asks for GPU times any more: forget them, so samples carry
    /// `gpu_ms: 0` and no stages instead of stale ones.
    pub fn clear_gpu_times(&mut self) {
        self.gpu.clear();
        self.gpu_total = None;
    }

    /// Frame generation multiplier now (`None` = off).
    pub fn set_multiplier(&mut self, active: Option<u8>) {
        self.multiplier = active;
    }

    /// The display refresh rate changed (monitor switch).
    pub fn set_refresh_hz(&mut self, hz: f32) {
        self.options.refresh_hz = hz;
    }

    /// Drain the present sink (latency, present and generated fps, the
    /// CSV). Every `sample_interval`, the new sample.
    pub fn poll(&mut self, now: Instant) -> Option<StatsSample> {
        while let Ok(record) = self.rx.try_recv() {
            self.presents.add(record.presented);
            if record.kind == FrameKind::Generated {
                self.generated.add(record.presented);
            }
            if let Some(capture) = record.capture {
                let ms = record.presented.saturating_duration_since(capture).as_secs_f32() * 1000.0;
                self.latency.push_back((record.presented, ms, record.kind));
            }
            if let Some(log) = &mut self.log
                && let Err(e) = log.write(&record)
            {
                tracing::error!("latency log: {e}; stopping it");
                self.log = None;
            }
        }
        if now < self.next_sample {
            return None;
        }
        self.next_sample = now + self.options.sample_interval;
        let sample = self.sample(now);
        self.latest = Some(sample.clone());
        Some(sample)
    }

    /// The last sample (for the panel between samples).
    pub fn latest(&self) -> Option<&StatsSample> {
        self.latest.as_ref()
    }

    /// Flush and close the CSV.
    pub fn close(mut self) -> Result<()> {
        // Presents still queued belong in the CSV.
        let _ = self.poll(Instant::now());
        if let Some(log) = &mut self.log {
            log.flush()?;
        }
        Ok(())
    }

    fn sample(&mut self, now: Instant) -> StatsSample {
        // Rates of 1.x: the game rate is new frames; `poll_fps` counts every
        // capture.
        let poll_fps = self.captures.per_second(now);
        let capture_fps = self.new_frames.per_second(now);
        let present_fps = self.presents.per_second(now);
        let generated_fps = self.generated.per_second(now);
        expire(&mut self.render_ms, now, |e| e.0);
        expire(&mut self.latency, now, |e| e.0);
        let (latency_ms, latency_p95_ms) = latency_summary(self.latency.iter().map(|e| e.1));
        let n = self.render_ms.len() as f32;
        let render_ms =
            (!self.render_ms.is_empty()).then(|| self.render_ms.iter().map(|e| e.1).sum::<f32>() / n);
        let wait_ms =
            (!self.render_ms.is_empty()).then(|| self.render_ms.iter().map(|e| e.2).sum::<f32>() / n);
        let latency_by_kind = [FrameKind::Real, FrameKind::Generated]
            .into_iter()
            .filter_map(|kind| {
                let values: Vec<f32> = self.latency.iter().filter(|e| e.2 == kind).map(|e| e.1).collect();
                (!values.is_empty()).then(|| KindLatency {
                    kind: kind.as_str().to_owned(),
                    mean_ms: values.iter().sum::<f32>() / values.len() as f32,
                    max_ms: values.iter().copied().fold(0.0, f32::max),
                })
            })
            .collect();

        let stages: Vec<StageTime> = self
            .gpu
            .iter()
            .map(|(name, ms)| StageTime {
                name: name.clone(),
                ms: *ms as f32,
            })
            .collect();
        let gpu_ms = self.gpu_total.unwrap_or(0.0) as f32;
        let budgeted: Vec<StageTime> = stages.iter().filter(|s| !is_overlay(&s.name)).cloned().collect();
        let gpu_warning = gpu_budget_warning(&budgeted, budgeted.iter().map(|s| s.ms).sum(), capture_fps);
        StatsSample {
            capture_fps,
            present_fps,
            generated_fps,
            latency_ms,
            latency_p95_ms,
            gpu_ms,
            stages,
            dirty_fraction: self.dirty_fraction,
            tiles: self.tiles,
            multiplier: self.multiplier,
            gpu_warning,
            poll_fps,
            render_ms,
            wait_ms,
            latency_by_kind,
        }
    }
}

fn smooth(old: f64, new: f64) -> f64 {
    old * (1.0 - GPU_SMOOTHING) + new * GPU_SMOOTHING
}

/// The OSD, the panel and the bar over the game draw after the effects and
/// do not count against the budget.
fn is_overlay(label: &str) -> bool {
    label == "osd" || label == "toolbar"
}

/// Mean and 95th percentile (1.x `summarize`: the value at rank
/// `round(n · 0.95)`); zeros without samples.
fn latency_summary(values: impl Iterator<Item = f32>) -> (f32, f32) {
    let mut values: Vec<f32> = values.collect();
    if values.is_empty() {
        return (0.0, 0.0);
    }
    values.sort_by(f32::total_cmp);
    let mean = values.iter().sum::<f32>() / values.len() as f32;
    let rank = ((values.len() as f32 * 0.95 + 0.5) as usize).max(1) - 1;
    (mean, values[rank.min(values.len() - 1)])
}

/// The «la GPU no llega» warning (`gpu_budget_warning` of 1.x): the GPU
/// time of a frame against the refresh budget, with the heaviest stages.
///
/// As in 1.x, `refresh_hz` is the rate the frames must keep up with —
/// [`Stats`] passes the game frame rate (new captured frames per second) —
/// and the budget is never looser than 30 fps; under 5 fps (a still image)
/// nothing is checked. `heaviest` holds up to three stages, heaviest first
/// (1.x named only the first).
pub fn gpu_budget_warning(stages: &[StageTime], gpu_ms: f32, refresh_hz: f32) -> Option<GpuWarning> {
    if refresh_hz < MIN_BUDGET_FPS || stages.is_empty() {
        return None;
    }
    let budget_ms = 1000.0 / refresh_hz.max(TARGET_FPS);
    if gpu_ms <= budget_ms {
        return None;
    }
    let mut heaviest: Vec<(String, f32)> = stages.iter().map(|s| (s.name.clone(), s.ms)).collect();
    heaviest.sort_by(|a, b| b.1.total_cmp(&a.1));
    heaviest.truncate(HEAVIEST);
    Some(GpuWarning {
        budget_ms,
        gpu_ms,
        heaviest,
    })
}

/// What the panel shows besides the sample (`_stats_rows` of 1.x). The
/// session thread fills it (front P); the strings are already formatted.
#[derive(Debug, Clone, PartialEq, Default)]
pub struct PanelContext {
    /// Window title (not shown; kept for logs and the GUI).
    pub title: String,
    /// Profile, if any.
    pub profile: Option<String>,
    /// Mode, if any (new in 2.0).
    pub mode: Option<String>,
    /// SRCNN model (`none`, `2x16`, ...).
    pub model: String,
    /// `double_upscale` (×4) or not (×2).
    pub double_upscale: bool,
    /// Source size, after the crop.
    pub src: (u32, u32),
    /// Crop in effect (configured plus menu bar).
    pub crop: lirtup_config::Crop,
    /// Output size.
    pub dst: (u32, u32),
    /// `output_geometry`, `upsampler/downsampler` (1.x «Output» row).
    pub output: String,
    /// Effect chain labels, in order.
    pub chain: Vec<String>,
    /// `Native` or `MagpieFX`.
    pub engine: String,
    /// The post effects that are on (`Deband`, `CAS`, `Bloom`, `Vignette`,
    /// `LUT <preset>`, `Grain`).
    pub post: Vec<String>,
    /// Present mode, with `, new frames only` when it applies.
    pub present: String,
    /// Frame generation (`None`: no row, as 1.x when it is off).
    pub framegen: Option<FrameGenLine>,
}

/// The «Frame gen» row of the panel.
#[derive(Debug, Clone, PartialEq, Default)]
pub struct FrameGenLine {
    /// What runs: `x2 built-in FP16`, `auto x3 built-in, restarting lsfg`,
    /// `x2 lsfg-vk`, `lsfg-vk (LSFGVK_* env)`.
    pub text: String,
    /// Multiplier for the `~N fps` estimate (`None`: no estimate).
    pub multiplier: Option<u8>,
    /// After the estimate: `, pacing 16.7 ms` (built-in) or ` est.` (layer).
    pub suffix: String,
    /// Drawn as a warning (the built-in engine failed).
    pub warning: bool,
    /// The lsfg-vk layer adds its own latency after ours (`+ lsfg-vk`).
    pub layer: bool,
}

/// One panel row: label (empty continues the previous row), value, and
/// whether it is a warning (drawn in the warning color).
#[derive(Debug, Clone, PartialEq)]
struct Row {
    label: String,
    value: String,
    warning: bool,
}

impl Row {
    fn new(label: &str, value: impl Into<String>) -> Row {
        Row {
            label: label.to_owned(),
            value: value.into(),
            warning: false,
        }
    }

    fn warning(label: &str, value: impl Into<String>) -> Row {
        Row {
            warning: true,
            ..Row::new(label, value)
        }
    }
}

/// The rows of the panel, as 1.x `_stats_rows` (plus «Mode», new in 2.0,
/// and the tiles of the last frame in «Upscale»).
fn panel_rows(sample: &StatsSample, context: &PanelContext) -> Vec<Row> {
    let mut rows = vec![
        Row::new(
            "Game",
            format!(
                "{:5.1} fps new  ({:.0}/s polled)",
                sample.capture_fps, sample.poll_fps
            ),
        ),
        Row::new(
            "Shown",
            format!("{:5.1} fps", sample.present_fps)
                + &sample
                    .render_ms
                    .map(|ms| format!("  render {ms:.1} ms"))
                    .unwrap_or_default()
                + &sample
                    .wait_ms
                    .filter(|ms| *ms >= 0.05)
                    .map(|ms| format!(" (+{ms:.1} wait)"))
                    .unwrap_or_default(),
        ),
    ];
    if let Some(fg) = &context.framegen {
        let mut value = fg.text.clone();
        if let Some(m) = fg.multiplier {
            value += &format!("  ~{:.0} fps{}", sample.capture_fps * f32::from(m), fg.suffix);
        }
        rows.push(if fg.warning {
            Row::warning("Frame gen", value)
        } else {
            Row::new("Frame gen", value)
        });
    }
    let mut latency: Vec<String> = sample
        .latency_by_kind
        .iter()
        .map(|k| format!("{} {:.1} ms (max {:.0})", k.kind, k.mean_ms, k.max_ms))
        .collect();
    if !latency.is_empty() {
        if context.framegen.as_ref().is_some_and(|fg| fg.layer) {
            latency.push("+ lsfg-vk".to_owned());
        }
        rows.push(Row::new("Latency", latency.join("  ")));
    }
    if context.src != (0, 0) {
        let c = &context.crop;
        let mut source = format!("{}x{}", context.src.0, context.src.1);
        if c.top + c.bottom + c.left + c.right > 0 {
            source += &format!("  crop T{} B{} L{} R{}", c.top, c.bottom, c.left, c.right);
        }
        rows.push(Row::new("Source", source));
    }
    let mode = match sample.tiles {
        Some(tiles) => format!("tiles ({tiles}, {:.0} %)", sample.dirty_fraction * 100.0),
        None => "full frame".to_owned(),
    };
    let factor = if context.double_upscale { "x4" } else { "x2" };
    rows.push(Row::new("Upscale", format!("{} {factor}  {mode}", context.model)));
    for (i, label) in context.chain.iter().enumerate() {
        let ms = sample
            .stages
            .iter()
            .find(|s| &s.name == label)
            .map(|s| format!("  {:.2} ms", s.ms))
            .unwrap_or_default();
        rows.push(Row::new(
            if i == 0 { "Effects" } else { "" },
            format!("{label}{ms}"),
        ));
    }
    if !context.chain.is_empty() {
        rows.push(Row::new("", format!("({})", context.engine)));
        if let Some(w) = &sample.gpu_warning {
            let heaviest = w.heaviest.first().map_or("", |(name, _)| name.as_str());
            rows.push(Row::warning(
                "GPU",
                format!(
                    "{:.1} ms > {:.1} ms/frame, heaviest: {heaviest}",
                    w.gpu_ms, w.budget_ms
                ),
            ));
        }
    }
    rows.push(Row::new(
        "Output",
        format!("{}x{}  {}", context.dst.0, context.dst.1, context.output),
    ));
    rows.push(Row::new(
        "Post",
        if context.post.is_empty() {
            "none".to_owned()
        } else {
            context.post.join(", ")
        },
    ));
    rows.push(Row::new("Present", context.present.clone()));
    if let Some(mode) = &context.mode {
        rows.push(Row::new("Mode", mode.clone()));
    }
    rows.push(Row::new(
        "Profile",
        context.profile.clone().unwrap_or_else(|| "none".to_owned()),
    ));
    rows
}

